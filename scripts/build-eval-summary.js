#!/usr/bin/env node
/**
 * Generate eval/summary.json — the judged-quality + freshness block that
 * GET /snapshot serves to downstream consumers (the AI Product & Leadership
 * Studio). This replaces the previously hand-maintained file, which drifted
 * from the eval run because `npm run eval:judge` only writes the (gitignored)
 * eval/judge-results.json.
 *
 * Sources:
 *   - eval/judge-results.json   (npm run eval:judge)  → judged metrics, REQUIRED
 *   - eval/keyword-results.json (npm run eval)        → Keyword Hit@5, optional
 *   - Neon `documents.created_at`                     → real knowledgeFreshnessDays
 *
 * Citation Validity is an enforced-by-construction invariant (verified by
 * `npm run check`), so it is emitted as a constant, not measured here.
 *
 *   npm run eval:summary
 */
require("dotenv").config();
const fs = require("fs");
const path = require("path");

const EVAL_DIR = path.join(__dirname, "..", "eval");
const JUDGE = path.join(EVAL_DIR, "judge-results.json");
const KEYWORD = path.join(EVAL_DIR, "keyword-results.json");
const OUT = path.join(EVAL_DIR, "summary.json");

const pct = (x) => Math.round(x * 100);
const rel = (p) => path.relative(process.cwd(), p);
const readJson = (p) => {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch {
    return null;
  }
};

// Days since the newest document was ingested — the honest knowledge-base age.
// Null (→ the Studio's "Not reported") if the DB is unreachable, never a guess.
async function knowledgeFreshnessDays() {
  if (!process.env.DATABASE_URL) return null;
  let db;
  try {
    db = require("../src/rag/db");
    const { rows } = await db.query("SELECT max(created_at) AS latest FROM documents");
    const latest = rows[0] && rows[0].latest;
    if (!latest) return null;
    return Math.max(0, Math.floor((Date.now() - new Date(latest).getTime()) / 86_400_000));
  } catch (e) {
    console.error("freshness: DB unavailable —", e.message);
    return null;
  } finally {
    if (db && db.close) {
      try {
        await db.close();
      } catch {}
    }
  }
}

(async () => {
  const judge = readJson(JUDGE);
  if (!judge || !judge.metrics) {
    console.error(`No ${rel(JUDGE)} — run \`npm run eval:judge\` first.`);
    process.exit(1);
  }
  const m = judge.metrics;
  const c = judge.counts || {};
  const prev = readJson(OUT) || {};
  const keyword = readJson(KEYWORD);

  const answered = c.answered ?? null;
  const oos = c.out_of_scope ?? null;
  const correctnessPct = Math.round((m.mean_answer_correctness / 5) * 100);
  const refusalPct = m.out_of_scope_refusal == null ? null : pct(m.out_of_scope_refusal);

  // Judged rows — always regenerated from the latest judge run.
  const metrics = [
    { metric: "Faithfulness", score: pct(m.faithfulness_rate), passThreshold: 70, source: "LLM-judge" },
    { metric: "Answer Correctness", score: correctnessPct, passThreshold: 60, note: `${m.mean_answer_correctness.toFixed(2)}/5 rescaled to 0-100`, source: "LLM-judge" },
    { metric: "Semantic Hit@5", score: pct(m.semantic_hit5), passThreshold: 70, note: answered != null ? `${Math.round(m.semantic_hit5 * answered)}/${answered}` : undefined, source: "LLM-judge" },
    { metric: "Out-of-scope Refusal", score: refusalPct, passThreshold: 90, note: oos != null && refusalPct != null ? `${Math.round(m.out_of_scope_refusal * oos)}/${oos}` : undefined, source: "LLM-judge" },
  ];

  // Keyword Hit@5 — from the keyword eval if present, else carry the last-known
  // row forward (it changes rarely) so the dashboard keeps the metric.
  const prevKeyword = (prev.metrics || []).find((x) => x.metric === "Keyword Hit@5");
  if (keyword && typeof keyword.keywordHit5 === "number") {
    metrics.push({ metric: "Keyword Hit@5", score: pct(keyword.keywordHit5), passThreshold: 80, note: keyword.hits != null ? `${keyword.hits}/${keyword.total}` : undefined, source: "keyword-eval" });
  } else if (prevKeyword) {
    metrics.push(prevKeyword);
  }

  // Citation Validity — enforced by construction (verified by `npm run check`).
  metrics.push({ metric: "Citation Validity", score: 100, passThreshold: 100, note: "enforced by construction", source: "npm run check" });

  // pass flag + drop empty notes
  for (const row of metrics) {
    if (row.score != null && row.pass == null) row.pass = row.score >= row.passThreshold;
    if (row.note === undefined) delete row.note;
  }

  const evalRunAt = (judge.timestamp ? new Date(judge.timestamp) : new Date()).toISOString().slice(0, 10);
  const freshness = await knowledgeFreshnessDays();

  const summary = {
    _comment:
      "GENERATED by `npm run eval:summary` (scripts/build-eval-summary.js) from eval/judge-results.json + eval/keyword-results.json, with knowledgeFreshnessDays computed live from the newest document in the KB. Surfaced by GET /snapshot. Do NOT hand-edit — re-run the generator.",
    evalRunAt,
    knowledgeFreshnessDays: freshness,
    metrics: metrics.filter((x) => x.score != null),
    derived: {
      retrievalQuality: pct(m.semantic_hit5),
      citationAccuracy: 100,
      hallucinationRate: pct(m.hallucination_rate),
    },
  };

  fs.writeFileSync(OUT, JSON.stringify(summary, null, 2) + "\n");
  console.log(
    `Wrote ${rel(OUT)} — evalRunAt ${evalRunAt}, freshness ${freshness == null ? "null (Not reported)" : freshness + "d"}, ${summary.metrics.length} metrics.`,
  );
  process.exit(0);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
